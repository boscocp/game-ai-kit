#!/usr/bin/env bash
# Resolve requirements.in into requirements.lock: every package the generator
# installs, at one version, with the sha256 of the file pip chose.
#
# Run by hand when requirements.in changes, never by bootstrap. The lock is
# what makes two machines install the same bytes; resolving at install time
# would make it whatever was newest that day.
#
# pip has no lock command, but `pip install --dry-run --report` writes down
# what it would install and the hash of each file, which is a lock in all but
# name. Python's standard library turns the report into requirement lines.
#
# Usage: tools/artgen/lock.sh ENVIRONMENT_DIR
set -euo pipefail

here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
home=${1:?usage: lock.sh ENVIRONMENT_DIR}
report=$(mktemp)
trap 'rm -f "$report"' EXIT

PIP_CACHE_DIR="$home/cache/pip" XDG_CACHE_HOME="$home/cache/xdg" \
  "$home/venv/bin/python" -m pip install --quiet --dry-run --ignore-installed \
  --index-url https://pypi.org/simple --extra-index-url https://download.pytorch.org/whl/cu128 \
  --report "$report" -r "$here/requirements.in"

python3 -I - "$report" > "$here/requirements.lock" <<'PY'
import hashlib, json, sys, urllib.request
report = json.load(open(sys.argv[1]))
print("# Generated by tools/artgen/lock.sh from requirements.in. Do not edit.")
for item in sorted(report["install"], key=lambda item: item["metadata"]["name"].lower()):
    name, version = item["metadata"]["name"], item["metadata"]["version"]
    archive = item["download_info"]["archive_info"]
    # PyPI reports `hashes`; the PyTorch index the older `hash`, "sha256=...",
    # or, for the packages it mirrors, nothing -- then the file is hashed here.
    digest = archive.get("hashes", {}).get("sha256") or archive.get("hash", "").removeprefix("sha256=")
    if not digest:
        with urllib.request.urlopen(item["download_info"]["url"]) as response:
            digest = hashlib.sha256(response.read()).hexdigest()
    print(f"{name}=={version} --hash=sha256:{digest}")
PY
echo "lock: $(grep -c '==' "$here/requirements.lock") packages in requirements.lock"
